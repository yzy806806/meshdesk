// Load reads and parses a YAML config from path.
//
// The YAML decoder is configured with KnownFields(false) (the yaml.v3
// default), so unknown top-level sections — e.g. a leftover xray: block
// from a pre-refactor config — are silently ignored rather than causing
// a hard-fail. A warning is logged for each unrecognised top-level key
// so operators can spot stale sections during cleanup.
func Load(path string) (*Config, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read config: %w", err)
	}
	cfg := Default()
	if err := yaml.Unmarshal(data, cfg); err != nil {
		return nil, fmt.Errorf("parse config: %w", err)
	}

	// Warn about unrecognised top-level keys (e.g. leftover xray: section).
	warnUnknownTopLevelKeys(data)
	// Detect deprecated totp_secret in config.yaml (removed field).
	// The TOTP encryption key is now node-local at /var/lib/meshdesk/totp/master.key.
	if legacySecret := extractLegacyTOTPSecret(data); legacySecret != "" {
		cfg.Auth.legacyTOTPSecret = legacySecret
		log.Printf("[WARNING] config.yaml contains deprecated field 'totp_secret' — " +
			"TOTP encryption now uses node-local /var/lib/meshdesk/totp/master.key. " +
			"The config field is ignored and should be removed.")
	}
	if cfg.Mesh.Port == 0 {
		cfg.Mesh.Port = DefaultMeshPort
	}
	// TUN config defaults for MeshConfig fields.
	if cfg.Mesh.TunMTU == 0 {
		cfg.Mesh.TunMTU = DefaultTunMTU
	}
	if cfg.Mesh.TunName == "" && cfg.Mesh.TunEnabled {
		cfg.Mesh.TunName = "mesh0"
	}
	// DNS config defaults.
	if cfg.Mesh.DNSPort == 0 && cfg.Mesh.DNSEnabled {
		cfg.Mesh.DNSPort = 5353
	}
	// Backward compatibility: if the top-level tun: section has fields
	// set and the mesh.* fields don't, migrate from tun: to mesh.
	if cfg.Tun.Enabled && !cfg.Mesh.TunEnabled {
		cfg.Mesh.TunEnabled = true
	}
	if cfg.Tun.Subnet != "" && cfg.Mesh.MeshCIDR == "" {
		cfg.Mesh.MeshCIDR = cfg.Tun.Subnet
	}
	if cfg.Tun.Name != "" && cfg.Mesh.TunName == "" {
		cfg.Mesh.TunName = cfg.Tun.Name
	}
	if cfg.Tun.MTU != 0 && cfg.Mesh.TunMTU == 0 {
		cfg.Mesh.TunMTU = cfg.Tun.MTU
	}
	if len(cfg.Tun.SubnetProxies) > 0 && len(cfg.Mesh.SubnetProxy) == 0 {
		cfg.Mesh.SubnetProxy = cfg.Tun.SubnetProxies
	}
	// P2P config: memberlist retired — defaults are minimal.
	// Peer reality defaults: server_name and short_id have standard
	// values shared across the mesh — users only write public_key.
	for i := range cfg.Peers {
		if cfg.Peers[i].Reality == nil {
			cfg.Peers[i].Reality = &RealityPeerConfig{}
		}
		if cfg.Peers[i].Reality.ServerName == "" {
			cfg.Peers[i].Reality.ServerName = "www.microsoft.com"
		}
		if cfg.Peers[i].Reality.ShortID == "" {
			cfg.Peers[i].Reality.ShortID = "0123456789abcdef"
		}
		if cfg.Peers[i].Reality.TLSFingerprint == "" {
			cfg.Peers[i].Reality.TLSFingerprint = "chrome"
		}
	}
	// TUN defaults: enabled by default with standard mesh CIDR.
	if cfg.Mesh.TunName == "" {
		cfg.Mesh.TunName = "mesh0"
	}
	if cfg.Mesh.MeshCIDR == "" {
		cfg.Mesh.MeshCIDR = "10.100.0.0/24"
	}
	if cfg.P2P.RelayMode == "" && cfg.P2P.Enabled {
		cfg.P2P.RelayMode = "auto"
	}
	if cfg.P2P.MaxRelayHops == 0 && cfg.P2P.Enabled {
		cfg.P2P.MaxRelayHops = 2
	}
	// Backward compatibility: if the legacy advertise_endpoint field is set
	// and advertise_endpoints is not, migrate the single endpoint to the list.
	if cfg.P2P.AdvertiseEndpoint != "" && len(cfg.P2P.AdvertiseEndpoints) == 0 {
		cfg.P2P.AdvertiseEndpoints = []string{cfg.P2P.AdvertiseEndpoint}
	}
	if cfg.Monitoring.Interval == 0 {
		cfg.Monitoring.Interval = 15
	}
	if cfg.Monitoring.Port == 0 {
		cfg.Monitoring.Port = 4191
	}
	if cfg.WebSSH.Port == 0 {
		cfg.WebSSH.Port = 2222
	}
	if cfg.WebSSH.DialTimeout == 0 {
		cfg.WebSSH.DialTimeout = 10
	}
	if cfg.WebSSH.ReadDeadline == 0 {
		cfg.WebSSH.ReadDeadline = 300
	}
	if cfg.WebSSH.WriteDeadline == 0 {
		cfg.WebSSH.WriteDeadline = 10
	}
	if cfg.WebSSH.MaxSessions == 0 {
		cfg.WebSSH.MaxSessions = 256
	}
	if cfg.Transfer.MaxFileSize == 0 {
		cfg.Transfer.MaxFileSize = DefaultMaxFileSize
	}
	if cfg.Transfer.UploadDir == "" {
		cfg.Transfer.UploadDir = DefaultUploadDir
	}
	// Auth config defaults.
	if cfg.Auth.TOTPIssuer == "" {
		cfg.Auth.TOTPIssuer = "MeshDesk"
	}
	if cfg.Auth.TOTPWindow == 0 {
		cfg.Auth.TOTPWindow = 1
	}
	if cfg.Auth.StepUpTimeout == 0 {
		cfg.Auth.StepUpTimeout = 300
	}
	// Enable persistent TOTP storage by default in production (when
	// loaded from config file). Tests use config.Default() which
	// leaves this empty for in-memory mode.
	if cfg.Auth.TOTPStoreDir == "" {
		cfg.Auth.TOTPStoreDir = DefaultTOTPStoreDir
	}
	// Proxy config defaults.
	if cfg.Proxy.ChunkerStrategy == "" {
		cfg.Proxy.ChunkerStrategy = "bounded-4k-64k"
	}
	if cfg.Proxy.Circuit.IdleTimeout == 0 {
		cfg.Proxy.Circuit.IdleTimeout = 300
	}
	if cfg.Proxy.Circuit.KeepaliveInterval == 0 {
		cfg.Proxy.Circuit.KeepaliveInterval = 30
	}
	if cfg.Proxy.Circuit.NACKTimeout == 0 {
		cfg.Proxy.Circuit.NACKTimeout = 5
	}
	if cfg.Proxy.Circuit.OrphanTimeout == 0 {
		cfg.Proxy.Circuit.OrphanTimeout = 30
	}
	if cfg.Proxy.Circuit.MaxReassemblyWindow == 0 {
		cfg.Proxy.Circuit.MaxReassemblyWindow = 256
	}
	if len(cfg.Proxy.Exit.AllowedPorts) == 0 && !cfg.Proxy.Exit.AllowAllPorts {
		cfg.Proxy.Exit.AllowedPorts = []int{80, 443}
	}
	if cfg.Proxy.Exit.AuditRetentionDays == 0 {
		cfg.Proxy.Exit.AuditRetentionDays = 7
	}
	// SOCKS5 config defaults.
	if cfg.Proxy.SOCKS5.Enabled {
		if len(cfg.Proxy.SOCKS5.AllowedPorts) == 0 && !cfg.Proxy.SOCKS5.AllowAllPorts {
			cfg.Proxy.SOCKS5.AllowedPorts = []int{80, 443}
		}
		if cfg.Proxy.SOCKS5.DialTimeoutSec == 0 {
			cfg.Proxy.SOCKS5.DialTimeoutSec = 30
		}
		if cfg.Proxy.SOCKS5.IdleTimeoutSec == 0 {
			cfg.Proxy.SOCKS5.IdleTimeoutSec = 300
		}
		if cfg.Proxy.SOCKS5.MaxConnections == 0 {
			cfg.Proxy.SOCKS5.MaxConnections = 256
		}
	}
	// Relay config defaults.
	if cfg.Proxy.Relay.JitterMinMs == 0 {
		cfg.Proxy.Relay.JitterMinMs = 5
	}
	if cfg.Proxy.Relay.JitterMaxMs == 0 {
		cfg.Proxy.Relay.JitterMaxMs = 50
	}
	if cfg.Proxy.Relay.MaxCircuits == 0 {
		cfg.Proxy.Relay.MaxCircuits = 1024
	}
	if cfg.Proxy.Relay.MaxQueueDepth == 0 {
		cfg.Proxy.Relay.MaxQueueDepth = 256
	}
	// Path selection defaults.
	if cfg.Proxy.PathSelection.Mode == "" {
		cfg.Proxy.PathSelection.Mode = "manual"
	}
	if cfg.Proxy.PathSelection.Strategy == "" {
		cfg.Proxy.PathSelection.Strategy = "latency"
	}
	if cfg.Proxy.PathSelection.MaxRelaysPerPath == 0 {
		cfg.Proxy.PathSelection.MaxRelaysPerPath = 2
	}
	if cfg.Proxy.PathSelection.ProbeTimeoutSec == 0 {
		cfg.Proxy.PathSelection.ProbeTimeoutSec = 3
	}
	if cfg.Proxy.PathSelection.ProbeConcurrency == 0 {
		cfg.Proxy.PathSelection.ProbeConcurrency = 8
	}
	if cfg.Proxy.PathSelection.MaxCandidates == 0 {
		cfg.Proxy.PathSelection.MaxCandidates = 10
	}
	if cfg.Proxy.PathSelection.ProbeCacheTTLSec == 0 {
		cfg.Proxy.PathSelection.ProbeCacheTTLSec = 30
	}
	// Join config defaults.
	if cfg.Join.Enabled && cfg.Join.ListenAddr == "" {
		cfg.Join.ListenAddr = ":8443"
	}
	if cfg.Join.Enabled && cfg.Join.TokenLifetime == 0 {
		cfg.Join.TokenLifetime = 1800 // 30 minutes
	}
	// TUN config defaults.
	if cfg.Tun.Enabled && cfg.Tun.MTU == 0 {
		cfg.Tun.MTU = DefaultTunMTU
	}
	// ACL config defaults.
	if cfg.ACL.DefaultPolicy == "" {
		cfg.ACL.DefaultPolicy = ACLActionAllow
	}
	// Logging config defaults.
	if cfg.Logging.LogFile != "" {
		if cfg.Logging.LogMaxSize == 0 {
			cfg.Logging.LogMaxSize = DefaultLogMaxSize
		}
		if cfg.Logging.LogMaxBackups == 0 {
			cfg.Logging.LogMaxBackups = DefaultLogMaxBackups
		}
	}
	return cfg, nil
}

// Save writes the config to path as YAML.
func Save(path string, cfg *Config) error {
	data, err := yaml.Marshal(cfg)
	if err != nil {
		return fmt.Errorf("marshal config: %w", err)
	}
	if err := os.WriteFile(path, data, 0600); err != nil {
		return fmt.Errorf("write config: %w", err)
	}
	return nil
}

// LegacyTOTPSecret returns the deprecated totp_secret value found in
// config.yaml during Load(), or empty string if none. Used for one-time
// migration to the node-local master secret at /var/lib/meshdesk/totp/master.key.
func (a *AuthConfig) LegacyTOTPSecret() string {
	return a.legacyTOTPSecret
}

// extractLegacyTOTPSecret scans raw YAML bytes for a top-level
// auth.totp_secret field and returns its string value if present.
// This is needed because the TOTPSecret struct field was removed;
// the value is captured for migration only.
func extractLegacyTOTPSecret(data []byte) string {
	var raw map[string]map[string]any
	if err := yaml.Unmarshal(data, &raw); err != nil {
		return ""
	}
	auth, ok := raw["auth"]
	if !ok {
		return ""
	}
	secret, ok := auth["totp_secret"]
	if !ok {
		return ""
	}
	s, ok := secret.(string)
	if !ok {
		return ""
	}
	return s
}

// knownTopLevelKeys is the set of top-level YAML keys recognised by
// the Config struct. Any key not in this set is considered unknown
// and will trigger a warning during Load().
var knownTopLevelKeys = map[string]bool{
	"node":       true,
	"mesh":       true,
	"peers":      true,
	"p2p":        true,
	"monitoring": true,
	"webssh":     true,
	"auth":       true,
	"transfer":   true,
	"proxy":      true,
	"reality":    true,
	"join":       true,
	"tun":        true,
	"acl":        true,
	"logging":    true,
}

// warnUnknownTopLevelKeys unmarshals the raw YAML into a generic map
// and logs a warning for every top-level key that is not part of the
// Config struct. This helps operators identify stale sections (e.g.
// a leftover xray: block from the pre-refactor era) without causing
// a hard failure — the config still loads successfully.
func warnUnknownTopLevelKeys(data []byte) {
	var raw map[string]any
	if err := yaml.Unmarshal(data, &raw); err != nil {
		return
	}
	for key := range raw {
		if !knownTopLevelKeys[key] {
			log.Printf("[WARNING] config.yaml contains unknown top-level section '%s' — "+
				"it is ignored and can be safely removed.", key)
		}
	}
}
