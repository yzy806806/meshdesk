// MeshConfig holds mesh-level settings.
type MeshConfig struct {
	Port int `yaml:"port"` // mesh/Reality listen port

	// Zone is this node's zone tag (free-form string, e.g. "cn", "us",
	// "uk"). Peers with the SAME zone value use UDP P2P (multipath +
	// hole-punching); peers with a DIFFERENT zone (or unknown) use
	// Reality TLS only. Empty = unknown (conservative: Reality for all).
	Zone string `yaml:"zone,omitempty"`

	// --- TUN virtual network interface ---

	// TunEnabled controls whether the TUN device is created on startup.
	// When true, the node creates a TUN interface, allocates a VirtualIP
	// via IPAM, and syncs kernel routes for peer VirtualIPs.
	// Default: false. Requires CAP_NET_ADMIN or root.
	TunEnabled bool `yaml:"tun_enabled,omitempty"`

	// MeshCIDR is the CIDR subnet for the TUN interface (e.g. "10.144.144.0/24").
	// The node's VirtualIP is allocated from this subnet by the IPAM
	// deterministic allocator. Required when TunEnabled is true.
	MeshCIDR string `yaml:"mesh_cidr,omitempty"`

	// SubnetProxy is a list of local CIDR subnets that this node
	// advertises as reachable through its TUN interface (e.g. a LAN
	// behind it). Other nodes add kernel routes for these subnets
	// via this node's VirtualIP.
	SubnetProxy []string `yaml:"subnet_proxy,omitempty"`

	// TunName is the desired TUN interface name (e.g. "mesh0").
	// If empty, defaults to "mesh0".
	TunName string `yaml:"tun_name,omitempty"`

	// TunMTU is the MTU for the TUN interface. Default: 1400.
	TunMTU int `yaml:"tun_mtu,omitempty"`

	// StaticVirtualIP forces a specific VirtualIP instead of using IPAM
	// allocation. When set, the node uses this IP regardless of peer
	// state. Use only when IPAM cannot converge (e.g., single-node
	// testing, NAT-separated nodes with no relay).
	// Format: "10.100.0.2". The IP must be within mesh_cidr.
	StaticVirtualIP string `yaml:"static_virtual_ip,omitempty"`

	// --- Mesh DNS server ---

	// DNSEnabled controls whether the built-in lightweight DNS server
	// is started. When true, the node listens on DNSPort (UDP) and
	// resolves <hostname>.mesh queries to the corresponding peer's
	// VirtualIP using gossip-synchronized node metadata.
	// Default: false. Only meaningful when both TUN and P2P gossip
	// are enabled (DNS resolution requires VirtualIPs from gossip).
	DNSEnabled bool `yaml:"dns_enabled,omitempty"`

	// DNSPort is the UDP port for the built-in DNS server.
	// Default: 5353. Set to 53 to act as the mesh-wide resolver
	// (requires CAP_NET_BIND_SERVICE or root).
	DNSPort int `yaml:"dns_port,omitempty"`

	// FileTransferPaths restricts the cluster FileServer (0x1F4) to
	// these directory prefixes. Empty = serve any path (peer
	// authorization still applies via ACL).
	FileTransferPaths []string `yaml:"file_transfer_paths,omitempty"`
}

// P2pConfig holds settings for the P2P dynamic networking layer
// (gossip discovery, NAT traversal, dynamic join).
// When Enabled is false, the node uses static peers only (backward compat).
type P2pConfig struct {
	// Enabled controls whether dynamic P2P networking is active.
	Enabled bool `yaml:"enabled,omitempty"`

	// Seeds is the list of known mesh endpoints used to
	// bootstrap the mesh cluster.
	Seeds []string `yaml:"seeds,omitempty"`

	// RelayMode controls how relay fallback is handled:
	//   "auto"     — automatically select relay peers (default)
	//   "manual"   — use only manually configured relay peers
	//   "disabled" — no relay fallback (direct-only)
	RelayMode string `yaml:"relay_mode,omitempty"`

	// MaxRelayHops is the maximum number of relay hops for relayed connections.
	MaxRelayHops int `yaml:"max_relay_hops,omitempty"`

	// AdvertiseEndpoints is a list of explicit mesh endpoints (host:port)
	// that this node advertises to peers via META. When set, they override
	// the auto-detected local IP. Use this when the node is behind NAT and you
	// know the public IP:port mapping, or when auto-detection would pick the
	// wrong interface (e.g., Docker, multi-homed hosts, dual-stack IPv4/IPv6).
	AdvertiseEndpoints []string `yaml:"advertise_endpoints,omitempty"`

	// AdvertiseEndpoint is a legacy field for backward compatibility.
	// If set, it is treated as a single-element AdvertiseEndpoints list
	// during config loading. Deprecated: use advertise_endpoints instead.
	AdvertiseEndpoint string `yaml:"advertise_endpoint,omitempty"`
}

// PeerConfig describes a single mesh peer.
type PeerConfig struct {
	PublicKey    string   `yaml:"public_key"`
	Endpoint     string   `yaml:"endpoint"`     // host:port; empty for roaming
	AllowedIPs   []string `yaml:"allowed_ips"`  // v2: kept for routing table compatibility
	Capabilities []string `yaml:"capabilities"` // what this peer can do on us

	// Zone is the peer's zone tag (free-form, e.g. "cn", "us"). The
	// connection policy: SAME zone as ours → UDP P2P; different or
	// unknown (empty) → Reality TLS only. This is the primary
	// transport-selection signal.
	Zone string `yaml:"zone,omitempty"`

	// Reality holds per-peer Reality TLS transport configuration.
	// In v2, this is the only transport mode. See docs/MESHDESK_V2_DESIGN.md.
	Reality *RealityPeerConfig `yaml:"reality,omitempty"`

	// ServiceManage holds the list of service names this peer is allowed to
	// manage (start/stop/restart). Only meaningful when "service_manage"
	// appears in Capabilities. If empty with service_manage present, the
	// peer can manage all services (not recommended).
	ServiceManage []string `yaml:"service_manage,omitempty"`

	// FileTransferPaths restricts file_transfer capability to specific
	// directory prefixes. If empty with file_transfer present, no path
	// restriction is enforced (peer can access any path).
	FileTransferPaths []string `yaml:"file_transfer_paths,omitempty"`

	// MonitorScopes restricts monitor_read/monitor_write to specific
	// metric categories. If empty, all metrics are accessible.
	MonitorScopes []string `yaml:"monitor_scopes,omitempty"`
}

// RealityPeerConfig holds per-peer Reality TLS client-side configuration.
// Used when a peer's obfuscation mode is "reality".
type RealityPeerConfig struct {
	// ServerName is the SNI hostname sent in the TLS ClientHello.
	// e.g. "www.apple.com". Must match one of the server's accepted
	// server_names.
	ServerName string `yaml:"server_name"`

	// PublicKey is the server's X25519 public key (hex-encoded).
	// Used client-side to derive the REALITY auth key via ECDH.
	PublicKey string `yaml:"public_key"`

	// ShortID is the per-client short ID for REALITY authentication
	// (hex-encoded, up to 8 bytes). Must be in the server's short_ids list.
	ShortID string `yaml:"short_id"`

	// TLSFingerprint is the browser ClientHello to mimic.
	// Default: "chrome". Supported: chrome, firefox, safari, edge, ios, android.
	TLSFingerprint string `yaml:"tls_fingerprint,omitempty"`
}

// RealityServerConfig holds server-side Reality TLS configuration.
// Only needed on nodes that serve as relay/shared nodes accepting
// Reality TLS connections.
type RealityServerConfig struct {
	// Enabled controls whether the Reality TLS listener is started.
	Enabled bool `yaml:"enabled,omitempty"`

	// ListenAddr is the address to listen on. Default: ":443".
	ListenAddr string `yaml:"listen_addr,omitempty"`

	// ListenPort overrides the port in ListenAddr. Default: 443.
	ListenPort int `yaml:"listen_port,omitempty"`

	// Dest is the camouflage target — the real website to proxy
	// non-mesh traffic to (failing REALITY auth).
	// e.g. "www.apple.com:443"
	Dest string `yaml:"dest"`

	// ServerNames is the list of accepted SNI values.
	// Only connections presenting one of these SNIs pass auth.
	ServerNames []string `yaml:"server_names,omitempty"`

	// PrivateKey is the X25519 private key (hex-encoded) used
	// server-side for REALITY ECDH authentication.
	PrivateKey string `yaml:"private_key"`

	// ShortIDs is the list of accepted short IDs (hex-encoded).
	ShortIDs []string `yaml:"short_ids,omitempty"`
}

// MonitoringConfig holds monitoring/push settings.
type MonitoringConfig struct {
	Collectors []string `yaml:"collectors"` // peer IDs of collector nodes
	Interval   int      `yaml:"interval"`   // push interval in seconds
	Port       int      `yaml:"port"`       // mesh-internal port for metric pushes (default 4191)
}

// AuthConfig holds web UI auth settings.
type AuthConfig struct {
	WebUsers []WebUser `yaml:"web_users"`

	// TOTPIssuer is the issuer name embedded in otpauth:// URIs shown
	// in QR codes during 2FA enrollment. Default: "MeshDesk".
	TOTPIssuer string `yaml:"totp_issuer,omitempty"`

	// Require2FA, when true, mandates that all web dashboard users
	// complete TOTP enrollment before accessing any authenticated
	// endpoint. When false (default), 2FA enrollment is optional.
	Require2FA bool `yaml:"require_2fa,omitempty"`

	// TOTPWindow is the ±skew tolerance in time steps (default 1).
	// Each step is 30 seconds, so a value of 1 accepts codes from
	// the previous, current, and next 30-second windows.
	TOTPWindow int `yaml:"totp_window,omitempty"`

	// TOTPStoreDir is the directory for persistent TOTP encrypted state
	// storage. When set, TOTP enrollment state is encrypted and persisted
	// to <TOTPStoreDir>/users/<username>.enc, surviving process restarts.
	// When empty (default), TOTP state is in-memory only and lost on restart.
	// Production deployments should set this to /var/lib/meshdesk/totp.
	TOTPStoreDir string `yaml:"totp_store_dir,omitempty"`

	// StepUpTimeout is the lifetime of a step-up auth token in seconds
	// (default 300 = 5 minutes). After this period, sensitive operations
	// require re-authentication.
	StepUpTimeout int `yaml:"step_up_timeout,omitempty"`

	// AlertWebhookURL is an optional webhook endpoint for external
	// security alert notifications. When empty, alerts are only stored
	// in-memory and surfaced in the web UI.
	AlertWebhookURL string `yaml:"alert_webhook_url,omitempty"`

	// legacyTOTPSecret captures a deprecated totp_secret value found in
	// config.yaml during Load(). It is NOT serialized (no yaml tag) and
	// is used only for one-time migration to the node-local master secret.
	// Access via LegacyTOTPSecret() method.
	legacyTOTPSecret string `yaml:"-"`
}

// WebSSHConfig holds settings for the WebSSH bridge.
type WebSSHConfig struct {
	// Port is the mesh-internal port for the SSH server on the target node.
	// Default: 2222.
	Port int `yaml:"port"`

	// HostKey is the SSH host private key (PEM-encoded). If empty, an
	// Ed25519 key is auto-generated on startup.
	HostKey string `yaml:"host_key"`

	// Shell is the default shell to launch. If empty, auto-detected via
	// /etc/passwd, falling back to /bin/bash then /bin/sh.
	Shell string `yaml:"shell"`

	// DialTimeout is how long the web server node waits when dialing
	// the target node's SSH server over the mesh VPN (seconds, default 10).
	DialTimeout int `yaml:"dial_timeout"`

	// ReadDeadline is the WebSocket read deadline for idle sessions
	// (seconds, default 300 = 5 minutes).
	ReadDeadline int `yaml:"read_deadline"`

	// WriteDeadline is the WebSocket write deadline (seconds, default 10).
	WriteDeadline int `yaml:"write_deadline"`

	// MaxSessions limits concurrent terminal sessions per node (default 256).
	MaxSessions int `yaml:"max_sessions"`
}

